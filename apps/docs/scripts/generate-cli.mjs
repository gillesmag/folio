import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../..', import.meta.url));
const help = (args) =>
	execFileSync('cargo', ['run', '--quiet', '--locked', '-p', 'folio', '--', ...args, '--help'], {
		cwd: root,
		encoding: 'utf8',
		env: { ...process.env, NO_COLOR: '1', COLUMNS: '100', FOLIO_SERVER: '' }
	})
		.replace(/[\t ]+$/gm, '')
		.trimEnd();
const overview = help([]);
const section = overview.split('Commands:\n')[1]?.split('\nOptions:')[0];
if (!section) throw new Error('Cannot find the CLI command list');
const commands = [...section.matchAll(/^  ([a-z][a-z-]+)\s+/gm)]
	.map((match) => match[1])
	.filter((name) => name !== 'help');
if (commands.length === 0) throw new Error('No CLI commands found');
const pages = commands.map((name) => `## folio ${name}\n\n\`\`\`text\n${help([name])}\n\`\`\``);
const content = `---\ntitle: Command help\ndescription: Arguments and options generated from the folio executable.\n---\n\n{/* Generated by scripts/generate-cli.mjs. Do not edit by hand. */}\n\nRegenerate this page from the repository with \`pnpm --filter @folio/docs generate:cli\`.\n\n## folio\n\n\`\`\`text\n${overview}\n\`\`\`\n\n${pages.join('\n\n')}\n`;
writeFileSync(new URL('../content/docs/cli/commands.mdx', import.meta.url), content);
